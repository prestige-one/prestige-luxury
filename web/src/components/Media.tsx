"use client";

// The one image component for the whole site.
//
// Every `next/image` below the fold is lazy-loaded, so without a placeholder the page paints a
// row of blank white rectangles and only fills them in as the bytes arrive — which reads as
// "missing images". `Media` gives every image a tonal placeholder from first paint and fades it
// away once the image has decoded, so no image area is ever blank white.
//
// Props are `next/image`'s, unchanged (`fill`, `width`/`height`, `sizes`, `priority`, `className`,
// `alt`, `quality`, `style`, …), plus `tone` for the placeholder tint. `placeholder`/`blurDataURL`
// are handled here: a local hero/banner image listed in `content/blur.json` (generated by
// `crawl/blur-placeholders.mjs`) gets a real blurred preview instead of a flat tone.
import NextImage, { type ImageProps } from "next/image";
import { useCallback, useState } from "react";
import { isUnoptimized } from "@/lib/listing-format";
import blurJson from "../../content/blur.json";

const blurMap: Record<string, string> = blurJson;

/** Placeholder tints — existing theme tokens only. `ink` is for photos on a black section. */
const toneClass = { smoke: "bg-smoke", mist: "bg-mist", ink: "bg-ink" } as const;
const toneVar = {
  smoke: "var(--color-smoke)",
  mist: "var(--color-mist)",
  ink: "var(--color-ink)",
} as const;

export type MediaTone = keyof typeof toneClass;

export type MediaProps = Omit<ImageProps, "placeholder" | "blurDataURL" | "onLoad" | "ref"> & {
  /** Placeholder tint while the image loads. Default `smoke` (#f0f0f0). */
  tone?: MediaTone;
};

export default function Media({ tone = "smoke", className, style, fill, unoptimized, ...props }: MediaProps) {
  const [loaded, setLoaded] = useState(false);
  const show = useCallback(() => setLoaded(true), []);
  // A cached image can finish loading before React attaches `onLoad` — it would then never fire
  // and the placeholder would sit there for good. The ref runs on mount, after the browser has
  // had its say, so `complete` catches exactly that case.
  const settle = useCallback((img: HTMLImageElement | null) => {
    if (img?.complete) setLoaded(true);
  }, []);

  const src = props.src;
  const blurDataURL = typeof src === "string" ? blurMap[src] : undefined;
  const blur = blurDataURL ? ({ placeholder: "blur", blurDataURL } as const) : {};
  // Portal photos are served straight from the listing CDNs; they never go through the optimiser.
  const raw = unoptimized ?? (typeof src === "string" && isUnoptimized(src));

  const image = (
    <NextImage
      {...props}
      {...blur}
      fill={fill}
      unoptimized={raw}
      className={className}
      ref={settle}
      onLoad={show}
      // A fixed-size image has no wrapper to hold the placeholder, so it carries the tone itself
      // (the same trick next/image uses for blur placeholders) until its own pixels cover it.
      style={fill || loaded ? style : { backgroundColor: toneVar[tone], ...style }}
    />
  );

  if (!fill) return image;

  // `fill` images are absolutely positioned inside a relative parent, so the placeholder can be a
  // sibling covering the same box: it starts opaque and fades out over 400ms once the image is
  // there. Fading the layer above the image (rather than the image itself) keeps every caller's
  // own `opacity-*`/`transition-*` classes working exactly as before.
  return (
    <>
      {image}
      <span
        aria-hidden
        className={`pointer-events-none absolute inset-0 transition-opacity duration-[400ms] ease-out motion-reduce:transition-none ${
          toneClass[tone]
        } ${loaded ? "opacity-0" : "opacity-100"}`}
        style={blurDataURL ? { backgroundImage: `url("${blurDataURL}")`, backgroundSize: "cover", backgroundPosition: "center" } : undefined}
      />
    </>
  );
}
